def _render_chapter_page(
    code: str,
    chapter: dict[str, Any],
    blocks_by_point: dict[str, dict[str, dict[str, Any]]],
    manual_blocks: dict[str, str],
    *,
    prev_chapter: dict[str, Any] | None = None,
    next_chapter: dict[str, Any] | None = None,
) -> str:
    title = chapter["title"]

    chapter_nav_items = []
    if prev_chapter:
        prev_fn = f"{prev_chapter['ordinal']:02d}-{prev_chapter['slug']}.md"
        chapter_nav_items.append(f"[← 上一章：{prev_chapter['title']}]({prev_fn})")
    else:
        chapter_nav_items.append("这是第一章")

    chapter_nav_items.append("[返回课程概览](../index.md)")

    if next_chapter:
        next_fn = f"{next_chapter['ordinal']:02d}-{next_chapter['slug']}.md"
        chapter_nav_items.append(f"[下一章：{next_chapter['title']} →]({next_fn})")
    else:
        chapter_nav_items.append("这是最后一章")

    chapter_nav_bar = " ｜ ".join(chapter_nav_items)

    out = [
        GENERATED_COMMENT,
        f"# {title}",
        "",
        AI_BANNER,
        "",
        "[返回课程概览](../index.md) ｜ [学习计划](../plan.md) ｜ [考纲与范围](../syllabus.md) ｜ [练习与真题](../practice.md)",
        "",
        f"**章节导航**：{chapter_nav_bar}",
        "",
        "## 章节概览",
        "",
    ]
    for sec in chapter.get("sections", []):
        out.append(f"- **{sec['title']}**")
    out.extend(
        [
            "",
            "## 官方考核要求",
            "",
        ]
    )
    for sec in chapter.get("sections", []):
        out.append(f"### {sec['title']}")
        out.append("")
        out.append("| 知识点编号 | 能力层级 | 考纲原文短语 |")
        out.append("| --- | --- | --- |")
        for p in sec.get("points", []):
            out.append(f"| {p['id']} | {p['requirement']} | {p['quote']} |")
        out.append("")

    if chapter.get("chapter_focus"):
        out.extend(
            [
                "## 本章重点",
                "",
            ]
        )
        for focus in chapter["chapter_focus"]:
            if isinstance(focus, dict):
                text = focus.get("text", "")
                loc = focus.get("locator")
                if loc:
                    out.append(f"- **{text}**（考纲依据：`{loc}`）")
                else:
                    out.append(f"- **{text}**")
            else:
                out.append(f"- {focus}")
        out.append("")

    out.extend(
        [
            "## 核心要点精讲与记忆",
            "",
        ]
    )
    for sec in chapter.get("sections", []):
        for p in sec.get("points", []):
            pid = p["id"]
            point_blocks = blocks_by_point.get(pid, {})
            explain = point_blocks.get("explain")
            memorize = point_blocks.get("memorize")
            out.append(f"### 考点精讲：{pid}（{p['requirement']}）")
            out.append("")
            if explain and explain.get("text_md"):
                cleaned_explain = _clean_explain_headings(explain["text_md"].strip())
                out.append(cleaned_explain)
                out.append("")
            if memorize and memorize.get("text_md"):
                out.append("#### 记忆辅助")
                out.append("")
                out.append(memorize["text_md"].strip())
                out.append("")

    out.extend(
        [
            "## AI 仿真练习题",
            "",
        ]
    )
    for sec in chapter.get("sections", []):
        for p in sec.get("points", []):
            pid = p["id"]
            point_blocks = blocks_by_point.get(pid, {})
            drill = point_blocks.get("drill")
            if drill:
                qtype = drill.get("question_type", "题型自测")
                out.append(f"### 练习题：{pid}（{qtype}）")
                out.append("")
                out.append(drill.get("text_md", "").strip())
                out.append("")
                out.append("<details>")
                out.append("<summary>点击查看参考答案与解析</summary>")
                out.append("")
                out.append("**【参考答案与解析】**")
                out.append("")
                out.append(drill.get("answer_md", "").strip())
                out.append("")
                out.append("</details>")
                out.append("")

    out.extend(
        [
            "---",
            "",
            f"**章节导航**：{chapter_nav_bar}",
            "",
        ]
    )

    return "\n".join(out)


def render_course_pages(root: Path, code: str, *, target_dir: Path | None = None) -> list[Path]:
    evidence_path = root / "sources" / "jiangsu" / "courses" / code / "evidence.json"
    model_path = root / "sources" / "jiangsu" / "courses" / code / "knowledge-model.json"
    content_path = root / "sources" / "jiangsu" / "courses" / code / "content.json"

    if not evidence_path.is_file():
        raise FileNotFoundError(f"Missing evidence.json for course {code}")
    if not model_path.is_file():
        raise FileNotFoundError(f"Missing knowledge-model.json for course {code}")
    if not content_path.is_file():
        raise FileNotFoundError(f"Missing content.json for course {code}")

    evidence = json.loads(evidence_path.read_text(encoding="utf-8"))
    model = json.loads(model_path.read_text(encoding="utf-8"))
    content = json.loads(content_path.read_text(encoding="utf-8"))

    blocks_by_point: dict[str, dict[str, dict[str, Any]]] = {}
    for block in content.get("blocks", []):
        pid = block.get("point_id")
        if not pid:
            continue
        kind = block.get("kind")
        blocks_by_point.setdefault(pid, {})[kind] = block

    out_dir = target_dir or (root / "content" / "jiangsu" / "courses" / code)
    out_dir.mkdir(parents=True, exist_ok=True)
    knowledge_dir = out_dir / "knowledge"
    knowledge_dir.mkdir(parents=True, exist_ok=True)

    written: list[Path] = []
    repo_course_dir = root / "content" / "jiangsu" / "courses" / code

    def _read_existing(name: str) -> tuple[str, dict[str, str]]:
        t_file = out_dir / name
        f_file = repo_course_dir / name if repo_course_dir != out_dir else None
        text = ""
        if t_file.is_file():
            text = t_file.read_text(encoding="utf-8")
        elif f_file and f_file.is_file():
            text = f_file.read_text(encoding="utf-8")
        manual = get_existing_manual_blocks(t_file, f_file)
        return text, manual

    # 1. index.md
    idx_text, idx_manual = _read_existing("index.md")
    idx_content = _render_index(code, evidence, model, idx_text, idx_manual)
    p_idx = out_dir / "index.md"
    p_idx.write_text(idx_content, encoding="utf-8")
    written.append(p_idx)

    # 2. syllabus.md
    syl_text, syl_manual = _read_existing("syllabus.md")
    syl_content = _render_syllabus(code, evidence, model, syl_text, syl_manual)
    p_syl = out_dir / "syllabus.md"
    p_syl.write_text(syl_content, encoding="utf-8")
    written.append(p_syl)

    # 3. sources.md
    src_text, src_manual = _read_existing("sources.md")
    src_content = _render_sources(code, evidence, model, src_text, src_manual)
    p_src = out_dir / "sources.md"
    p_src.write_text(src_content, encoding="utf-8")
    written.append(p_src)

    # 4. plan.md
    pln_text, pln_manual = _read_existing("plan.md")
    pln_content = _render_plan(code, evidence, model, content, pln_text, pln_manual)
    p_pln = out_dir / "plan.md"
    p_pln.write_text(pln_content, encoding="utf-8")
    written.append(p_pln)

    # 5. practice.md
    prac_text, prac_manual = _read_existing("practice.md")
    prac_content = _render_practice(code, evidence, model, content, prac_text, prac_manual)
    p_prac = out_dir / "practice.md"
    p_prac.write_text(prac_content, encoding="utf-8")
    written.append(p_prac)

    # 6. review.md
    rev_text, rev_manual = _read_existing("review.md")
    rev_content = _render_review(code, evidence, model, content, rev_text, rev_manual)
    p_rev = out_dir / "review.md"
    p_rev.write_text(rev_content, encoding="utf-8")
    written.append(p_rev)

    # 7. 18 knowledge chapters
    chapters = model.get("chapters", [])
    for i, ch in enumerate(chapters):
        fname = f"{ch['ordinal']:02d}-{ch['slug']}.md"
        ch_text, ch_manual = _read_existing(f"knowledge/{fname}")
        prev_ch = chapters[i - 1] if i > 0 else None
        next_ch = chapters[i + 1] if i < len(chapters) - 1 else None
        ch_content = _render_chapter_page(
            code,
            ch,
            blocks_by_point,
            ch_manual,
            prev_chapter=prev_ch,
            next_chapter=next_ch,
        )
        p_ch = knowledge_dir / fname
        p_ch.write_text(ch_content, encoding="utf-8")
        written.append(p_ch)

    return written
