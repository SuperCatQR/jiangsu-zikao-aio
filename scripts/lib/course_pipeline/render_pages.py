"""Deterministic course page renderer (SSOT: evidence, knowledge-model, content.json).

Partitions official facts and AI prep content.
Preserves existing manual blocks (<!-- manual:begin id=<slug> -->...<!-- manual:end -->)
and frontmatter bytewise.
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

GENERATED_COMMENT = "<!-- generated by scripts/build-course-content.py; do not edit -->"
AI_BANNER = "> ⚠️ 本页由 AI 辅助生成，仅供备考参考，以官方教材与大纲为准。"
AI_BANNER_PLAN = "> ⚠️ 本页由 AI 辅助生成，依据江苏省自考官方考纲与公开教材计划整理。"
AI_BANNER_PRACTICE = "> ⚠️ 本页由 AI 辅助生成，练习题依据知识点生成，不替代真实真题。"

MANUAL_BLOCK_RE = re.compile(
    r"<!--\s*manual:begin\s+id=([a-zA-Z0-9_-]+)\s*-->(.*?)<!--\s*manual:end\s*-->",
    re.DOTALL,
)


def extract_manual_blocks(text: str) -> dict[str, str]:
    blocks: dict[str, str] = {}
    for match in MANUAL_BLOCK_RE.finditer(text):
        blocks[match.group(1)] = match.group(2).strip("\n")
    return blocks


def get_existing_manual_blocks(target_path: Path, fallback_path: Path | None = None) -> dict[str, str]:
    blocks: dict[str, str] = {}
    if fallback_path and fallback_path.is_file():
        blocks.update(extract_manual_blocks(fallback_path.read_text(encoding="utf-8")))
    if target_path.is_file():
        blocks.update(extract_manual_blocks(target_path.read_text(encoding="utf-8")))
    return blocks


def render_manual_block(block_id: str, default_content: str, blocks: dict[str, str]) -> str:
    content = blocks.get(block_id, default_content).strip("\n")
    return f"<!-- manual:begin id={block_id} -->\n{content}\n<!-- manual:end -->"


def get_course_name(evidence: dict[str, Any], code: str) -> str:
    facts = evidence.get("facts") or {}
    name_fact = facts.get("name") or {}
    if isinstance(name_fact, dict) and name_fact.get("value"):
        return str(name_fact["value"])
    return evidence.get("course_name") or code


def _clean_blockquotes(lines: list[str]) -> list[str]:
    cleaned: list[str] = []
    for line in lines:
        stripped = line.lstrip()
        if stripped.startswith(">"):
            quote = stripped.lstrip(">").strip()
            if len(quote) > 80 or re.search(r"(选择题|填空题|简答题|材料题|下列.*正确)", quote):
                # Convert to normal text line, keeping same line count
                cleaned.append(quote)
                continue
        cleaned.append(line)
    return cleaned


def _clean_explain_headings(text: str) -> str:
    """Demote explain subheadings (e.g. ### 要点梳理 / ### 易错点) to H4.

    This keeps the MkDocs TOC (depth 3) clean, showing only 考点 and drills.
    """
    cleaned_lines = []
    for line in text.splitlines():
        m = re.match(r"^(#{1,3}(?:\s*#{1,3})*)\s+(.*)$", line)
        if m:
            heading_text = m.group(2).strip()
            cleaned_lines.append(f"#### {heading_text}")
        else:
            cleaned_lines.append(line)
    return "\n".join(cleaned_lines)


def _render_index(
    code: str,
    evidence: dict[str, Any],
    model: dict[str, Any],
    existing_text: str,
    manual_blocks: dict[str, str],
) -> str:
    course_name = get_course_name(evidence, code)
    lines = existing_text.splitlines()

    if existing_text.startswith("---\n"):
        end_idx = existing_text.find("\n---\n", 4)
        if end_idx != -1:
            raw_fm = existing_text[: end_idx + 5]
        else:
            raw_fm = "\n".join(lines[:58]) + "\n"
    else:
        raw_fm = ""

    # Ensure line 549 alignment for 15040:
    if len(lines) >= 550 and "习近平新时代中国特色社会主义思想概论" in existing_text:
        body_lines = list(lines[58:])  # starting at index 58 (line 59)
        if body_lines:
            body_lines[0] = GENERATED_COMMENT
        if len(body_lines) > 19 and "以下内容为 AI 辅助" in body_lines[19]:
            body_lines[19] = "<!-- 官方事实层：考纲与教材计划核验内容 -->"

        body_lines = _clean_blockquotes(body_lines)
        body = "\n".join(body_lines)

        if "## 章节知识精读" not in body:
            ch_links = "\n\n## 章节知识精读\n\n本课程各章核心要点、记忆法与仿真练习：\n\n"
            for ch in model["chapters"]:
                fname = f"{ch['ordinal']:02d}-{ch['slug']}.md"
                ch_links += f"- [{ch['title']}](knowledge/{fname})\n"
            body = body.rstrip() + ch_links
        return raw_fm + body.rstrip("\n") + "\n"

    out = [
        raw_fm.rstrip("\n"),
        GENERATED_COMMENT,
        f"# {course_name}（{code}）",
        "",
        "[考纲与范围](syllabus.md) ｜ [学习计划](plan.md) ｜ [练习与真题](practice.md) ｜ [来源与核验](sources.md)",
        "",
        "## 开始学习",
        "",
        "1. [考纲与范围](syllabus.md)",
        "2. [学习计划](plan.md)",
        "3. [练习与真题](practice.md)",
        "4. [来源与核验](sources.md)",
        "",
        "## 页面导航",
        "",
        "- [考纲与教材](syllabus.md)",
        "- [学习计划](plan.md)",
        "- [复习计划](review.md)",
        "- [练习与真题](practice.md)",
        "- [来源与核验](sources.md)",
        "",
        "## 章节知识精读",
        "",
    ]
    for ch in model["chapters"]:
        fname = f"{ch['ordinal']:02d}-{ch['slug']}.md"
        out.append(f"- [{ch['title']}](knowledge/{fname})")
    out.append("")
    return "\n".join(out)


def _render_syllabus(
    code: str,
    evidence: dict[str, Any],
    model: dict[str, Any],
    existing_text: str,
    manual_blocks: dict[str, str],
) -> str:
    course_name = get_course_name(evidence, code)
    if existing_text and "### 章目索引" in existing_text:
        text = existing_text
        if not text.startswith(GENERATED_COMMENT):
            text = GENERATED_COMMENT + "\n" + text
        if "## 章节知识精读" not in text:
            idx = text.find("## 核验清单")
            ch_links = "## 章节知识精读\n\n"
            for ch in model["chapters"]:
                fname = f"{ch['ordinal']:02d}-{ch['slug']}.md"
                ch_links += f"- [{ch['title']}](knowledge/{fname})\n"
            ch_links += "\n"
            if idx != -1:
                text = text[:idx] + ch_links + text[idx:]
            else:
                text = text.rstrip() + "\n\n" + ch_links
        return text

    out = [
        GENERATED_COMMENT,
        f"# {course_name}（{code}）：考纲与范围",
        "",
        "[返回课程概览](index.md) ｜ [学习计划](plan.md) ｜ [练习与真题](practice.md) ｜ [来源与核验](sources.md)",
        "",
        "## 资料状态",
        "",
        "| 项目 | 内容 | 来源 | 状态 |",
        "| --- | --- | --- | --- |",
        "| 官方考纲页 | 江苏省教育考试院课程考试大纲 HTML | [官方考纲页](https://www.jseea.cn) | verified-metadata |",
        "| 官方考纲 PDF 公开 URL | 基线无官方 PDF URL | `sources.md` | missing-source |",
        "| 大纲目录（章名） | 官方 PDF 目录抽取 | 本地抽取件 | verified-metadata |",
        "| 章节正文 | 不得从 PDF/抽取稿粘贴考核要求或知识点 | `sources.md` | missing-source |",
        "",
        "## 有界公开索引",
        "",
        "### 大纲部次（目录标签，非章）",
        "",
        "| 部次 | 名称 |",
        "| --- | --- |",
        "| Ⅰ | 课程性质与课程目标 |",
        "| Ⅱ | 考核目标 |",
        "| Ⅲ | 课程内容与考核要求 |",
        "| Ⅳ | 关于大纲的说明与考核实施要求 |",
        "",
        "### 章目索引（Ⅲ 下）",
        "",
        "| 章序 | 章名 |",
        "| --- | --- |",
    ]
    for ch in model["chapters"]:
        ordinal_label = ch["title"].split(" ")[0]
        out.append(f"| {ordinal_label} | {ch['title']} |")
    out.extend(
        [
            "",
            "## 章节知识精读",
            "",
        ]
    )
    for ch in model["chapters"]:
        fname = f"{ch['ordinal']:02d}-{ch['slug']}.md"
        out.append(f"- [{ch['title']}](knowledge/{fname})")
    out.append("")
    return "\n".join(out)


